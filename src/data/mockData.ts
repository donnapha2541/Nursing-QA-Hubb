export const getWardResponsible = (
  wardResponsibles: Record<string, WardResponsible>,
  wardKey?: string
): WardResponsible => {
  if (!wardKey || wardKey === 'ALL') {
    return {
      headNurseName: '',
      headNursePosition: 'ผู้ตรวจการการพยาบาล',
      qaLeadName: '',
      phoneInternal: '',
      note: 'ครอบคลุมทุกตึก/หอผู้ป่วย',
    };
  }

  if (wardResponsibles[wardKey]) {
    return wardResponsibles[wardKey];
  }

  // Check matching by shortName or id or nameTh
  const allSubs = [
    ...IPD_SUB_DEPARTMENTS,
    ...ICU_SUB_DEPARTMENTS,
    ...SPECIAL_TREATMENT_SUB_DEPARTMENTS,
  ];

  const found = allSubs.find(
    (s) => s.id === wardKey || s.shortName === wardKey || s.nameTh.includes(wardKey)
  );

  if (found && wardResponsibles[found.id]) {
    return wardResponsibles[found.id];
  }

  return {
    headNurseName: '',
    headNursePosition: 'หัวหน้าหอผู้ป่วย',
    qaLeadName: '',
    phoneInternal: '',
    note: '',
  };
};
